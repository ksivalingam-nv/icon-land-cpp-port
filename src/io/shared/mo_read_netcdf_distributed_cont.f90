  !-----------------------------------------------------------------------------
  ! Some utility routines
  !-----------------------------------------------------------------------------

  FUNCTION get_read_buffer_size_1D(routine, io_data, out_buffer_size)
    CHARACTER(*), INTENT(IN) :: routine
    TYPE(t_distrib_read_data_cont), INTENT(IN) :: io_data
    INTEGER, INTENT(IN) :: out_buffer_size

    INTEGER :: get_read_buffer_size_1D

    TYPE(extent) :: io_chunk
    INTEGER :: io_chunk_size

    io_chunk = distrib_read_get_decomp(io_data%basic_data_index)
    io_chunk_size = io_chunk%size
    get_read_buffer_size_1D = io_chunk_size
    IF (out_buffer_size /= io_data%local_chunk%size) &
      CALL finish(routine, "mismatching out buffer size")

  END FUNCTION get_read_buffer_size_1D

  FUNCTION get_read_buffer_size_2D( &
    routine, io_data, out_buffer_shape, edim, opt_edim)
    CHARACTER(*), INTENT(IN) :: routine
    TYPE(t_distrib_read_data_cont), INTENT(IN) :: io_data
    INTEGER, INTENT(IN) :: out_buffer_shape(2)
    INTEGER, INTENT(OUT) :: edim
    INTEGER, OPTIONAL, INTENT(IN) :: opt_edim

    INTEGER :: get_read_buffer_size_2D(2)

    get_read_buffer_size_2D(1) =  &
      get_read_buffer_size_1D( &
        routine, io_data, out_buffer_shape(1))

    IF (PRESENT(opt_edim)) THEN
      edim = opt_edim
      IF (out_buffer_shape(2) < opt_edim) &
        CALL finish(routine, "2nd dimension of buffer is too small")
    ELSE
      edim = out_buffer_shape(2)
    END IF
    get_read_buffer_size_2D(2) = edim

  END FUNCTION get_read_buffer_size_2D

END MODULE mo_read_netcdf_distributed_cont
