    SUBROUTINE read_multi_var_3dint(vd, o)
      TYPE(t_ptr_3d_int), INTENT(INOUT) :: vd(:)
      INTEGER, INTENT(IN) :: o
      INTEGER :: i, j, k, idx

      INTEGER, ALLOCATABLE :: bufi_i(:,:), bufo_i(:,:,:)

      ALLOCATE(bufi_i(ish(1),ish(2)), bufo_i(osh(1),osh(2),osh(3)))
      CALL distrib_read_base( &
        ncid, vname, bufi_i, iod(1)%basic_data_index, start_ext_dim)
      IF (o .EQ. idx_blk_time) THEN
!ICON_OMP PARALLEL DO COLLAPSE(3) PRIVATE(idx)
        DO i = 1, osh(3)
          DO j = 1, osh(2)
            DO k = 1, osh(1)
              idx = MERGE(idx_1d(k,j), ish(1), idx_1d(k,j) .LE. ish(1))
              bufo_i(k,j,i) = bufi_i(idx,i)
            END DO
          END DO
        END DO
      ELSE IF(o .EQ. idx_lvl_blk) THEN
!ICON_OMP PARALLEL DO COLLAPSE(3) PRIVATE(idx)
        DO i = 1, osh(3)
          DO j = 1, osh(2)
            DO k = 1, osh(1)
              idx = MERGE(idx_1d(k,i), ish(1), idx_1d(k,i) .LE. ish(1))
              bufo_i(k,j,i) = bufi_i(idx,j)
            END DO
          END DO
        END DO
      END IF
      DO i = 1, SIZE(iod)
        IF (o .EQ. idx_blk_time) THEN
          DO j = 1, ish(2)
            CALL exchange_data( &
              p_pat=iod(i)%pat, lacc=.FALSE., &
              recv=vd(i)%p(:,:,j), send=bufo_i(:,:,j))
          END DO
        ELSE IF(o .EQ. idx_lvl_blk) THEN
          CALL exchange_data( &
            p_pat=iod(i)%pat, lacc=.FALSE., recv=vd(i)%p, send=bufo_i)
        END IF
      END DO
    END SUBROUTINE read_multi_var_3dint

